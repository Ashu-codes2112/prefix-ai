def demo_organization(session: Session) -> Organization | None:
    return session.scalar(select(Organization).where(Organization.is_demo.is_(True)))


def guest_user(session: Session, organization: Organization) -> User | None:
    return session.scalar(
        select(User).where(
            User.organization_id == organization.id,
            User.role == Role.DEMO_VIEWER,
            User.is_active.is_(True),
        )
    )


def demo_protocol_id(
    session: Session, organization_id: uuid.UUID, procedure_type_id: uuid.UUID
) -> uuid.UUID | None:
    """The approved protocol a demo booking follows: the hospital's SAMPLE one when someone
    has also approved their own for the same procedure, otherwise the only one."""
    approved = protocols_repo.list_approved_for_procedure(
        session, organization_id, procedure_type_id
    )
    samples = [protocol for protocol in approved if protocol.is_sample]
    chosen = (samples or approved)[:1]
    return chosen[0].id if chosen else None


def _slot_time(day: dt.date, slot: int, tz: ZoneInfo) -> dt.datetime:
    start = dt.datetime.combine(day, FIRST_SLOT, tzinfo=tz)
    return (start + dt.timedelta(minutes=SLOT_MINUTES * slot)).astimezone(dt.UTC)


def demo_slot(at: dt.datetime, timezone: str) -> dt.datetime:
    """The first booking slot at or after ``at``: 8 am to 3:45 pm local time, every 15 minutes,
    never on a Sunday."""
    tz = ZoneInfo(timezone)
    local = at.astimezone(tz)
    day = local.date()
    minutes = (local.hour - FIRST_SLOT.hour) * 60 + local.minute
    if local.second or local.microsecond:
        minutes += 1
    slot = max(0, -(-minutes // SLOT_MINUTES))
    if slot >= SLOTS_PER_DAY:
        day, slot = day + dt.timedelta(days=1), 0
    if day.weekday() == _SUNDAY:
        day, slot = day + dt.timedelta(days=1), 0
    return _slot_time(day, slot, tz)


def _future_slots(now: dt.datetime, timezone: str) -> list[dt.datetime]:
    """Every booking slot from ``MIN_LEAD`` ahead to ``BOOKING_DAYS`` ahead, in time order."""
    tz = ZoneInfo(timezone)
    today = now.astimezone(tz).date()
    earliest = now + MIN_LEAD
    slots = []
    for offset in range(BOOKING_DAYS + 1):
        day = today + dt.timedelta(days=offset)
        if day.weekday() == _SUNDAY:
            continue
        for slot in range(SLOTS_PER_DAY):
            start = _slot_time(day, slot, tz)
            if start >= earliest:
                slots.append(start)
    return slots


def _shortest_prep(
    session: Session, org_id: uuid.UUID, procedures: list[ProcedureType]
) -> tuple[dt.timedelta, ProcedureType] | None:
    """The procedure whose prep needs the least notice, so its released slot can be backfilled."""
    best: tuple[dt.timedelta, ProcedureType] | None = None
    for procedure in procedures:
        approved = protocols_repo.list_approved_for_procedure(session, org_id, procedure.id)
        lead = prep_lead(session, approved[0].id) if approved else None
        if lead is not None and (best is None or lead < best[0]):
            best = (lead, procedure)
    return best


def _add_backfill_scenario(
    session: Session,
    coordinator: StaffPrincipal,
    facility: Facility,
    procedure: ProcedureType,
    lead: dt.timedelta,
    waiting: list[uuid.UUID],
    *,
    now: dt.datetime,
) -> None:
    """A released slot and patients waiting for the same procedure, to try a backfill."""
    released = PatientService(session).create(
        coordinator,
        PatientCreate(
            first_name="Released",
            last_name="Patient",
            date_of_birth=dt.date(1980, 1, 1),
            phone="+919990000099",
            email=f"released@{DEMO_EMAIL_DOMAIN}",
            preferred_language="en",
            preferred_channel=MessageChannel.SMS,
            consent_to_message=True,
        ),
        now=now,
    )
    session.flush()
    scheduled_at = demo_slot(now + lead + dt.timedelta(days=1), facility.timezone)
    booked = AppointmentService(session).create(
        coordinator,
        AppointmentCreate(
            patient_id=released.id,
            facility_id=facility.id,
            procedure_type_id=procedure.id,
            protocol_id=demo_protocol_id(session, facility.organization_id, procedure.id),
            scheduled_at=scheduled_at,
        ),
        now=now,
    )
    AppointmentService(session).cancel(
        coordinator,
        booked.id,
        AppointmentCancel(reason=CancellationReason.PATIENT_REQUESTED),
        now=now,
    )
    local_day = scheduled_at.astimezone(ZoneInfo(facility.timezone)).date()
    for index, patient_id in enumerate(waiting):
        WaitlistService(session).add(
            coordinator,
            WaitlistEntryCreate(
                patient_id=patient_id,
                procedure_type_id=procedure.id,
                earliest_date=local_day - dt.timedelta(days=1),
                latest_date=local_day + dt.timedelta(days=2),
                priority=1 if index == 0 else 0,
            ),
        )


def _wipe_patient_data(session: Session, org: Organization) -> None:
    """Remove patients, bookings and everything that hangs off them. Protocols stay."""
    session.execute(delete(Escalation).where(Escalation.organization_id == org.id))
    session.execute(delete(Task).where(Task.organization_id == org.id))
    session.execute(delete(Appointment).where(Appointment.organization_id == org.id))
    session.execute(delete(Patient).where(Patient.organization_id == org.id))
    session.flush()


def populate_demo(
    session_factory: sessionmaker[Session],
    *,
    now: dt.datetime,
    admin_password: str | None = None,
) -> DemoResult:
    """Make the demo hospital look busy: patients, bookings across the next week, reminders
    already sent, some answers, a few escalations, and last month's procedures. Deterministic
    for a given ``now``'s day. ``admin_password`` is used only if the admin does not exist yet."""
    with session_factory() as session:
        hospital = ensure_demo_hospital(
            session, admin_password=admin_password or admin_password_from_env()
        )
        org, coordinator_user = hospital.organization, hospital.coordinator
        _wipe_patient_data(session, org)
        org_id = org.id
        coordinator = StaffPrincipal(
            user_id=coordinator_user.id, organization_id=org_id, role=Role.COORDINATOR
        )
        facilities = list(
            session.scalars(select(Facility).where(Facility.organization_id == org_id))
        )
        procedures = list(
            session.scalars(select(ProcedureType).where(ProcedureType.organization_id == org_id))
        )
        rng = random.Random(_SEED)  # noqa: S311 - reproducible demo data, not a secret
        # Each booking gets its own slot at its own facility, spread over the next week.
        bookings = rng.sample(
            [
                (facility, start)
                for facility in facilities
                for start in _future_slots(now, facility.timezone)
            ],
            PATIENT_COUNT,
        )
        appointment_count = 0
        backfill = _shortest_prep(session, org_id, procedures)
        waiting: list[uuid.UUID] = []
        for index in range(PATIENT_COUNT):
            first = rng.choice(_FIRST_NAMES)
            last = rng.choice(_LAST_NAMES)
            patient = PatientService(session).create(
                coordinator,
                PatientCreate(
                    first_name=first,
                    last_name=last,
                    date_of_birth=dt.date(
                        1950 + rng.randrange(55), rng.randrange(1, 13), rng.randrange(1, 28)
                    ),
                    phone=f"+9199900{index + 1:05d}",
                    email=f"patient{index + 1}@{DEMO_EMAIL_DOMAIN}",
                    preferred_language="hi" if index % 4 == 0 else "en",
                    preferred_channel=MessageChannel.SMS,
                    consent_to_message=True,
                    on_anticoagulant=index % 5 == 0,
                    diabetic_on_insulin=index % 7 == 0,
                    on_glp1_agonist=index % 9 == 0,
                ),
                now=now,
            )
            session.flush()
            facility, scheduled_at = bookings[index]
            procedure = procedures[index % len(procedures)]
            AppointmentService(session).create(
                coordinator,
                AppointmentCreate(
                    patient_id=patient.id,
                    facility_id=facility.id,
                    procedure_type_id=procedure.id,
                    protocol_id=demo_protocol_id(session, org_id, procedure.id),
                    scheduled_at=scheduled_at,
                ),
                now=now,
            )
            appointment_count += 1
            if (
                backfill is not None
                and procedure.id != backfill[1].id
                and len(waiting) < WAITING_PATIENTS
            ):
                waiting.append(patient.id)
        if backfill is not None:
            lead, slot_procedure = backfill
            _add_backfill_scenario(
                session, coordinator, facilities[0], slot_procedure, lead, waiting, now=now
            )
        session.commit()

    reminders = dispatch_due_reminders(
        session_factory,
        ConsoleProvider(),
        PassthroughTranslator(),
        now=now,
        batch_size=1000,
    )
    answers = _answer_some_check_ins(session_factory, org_id, now)
    escalations = _add_sample_escalations(session_factory, org_id, now)
    history = _add_history(session_factory, coordinator, now)
    logger.info(
        "demo.populated",
        patients=PATIENT_COUNT,
        appointments=appointment_count,
        history=history,
    )
    return DemoResult(
        organization_id=org_id,
        patients=PATIENT_COUNT,
        appointments=appointment_count,
        reminders_sent=reminders.get("sent", 0),
        answers=answers,
        escalations=escalations,
    )


def _add_history(
    session_factory: sessionmaker[Session], coordinator: StaffPrincipal, now: dt.datetime
) -> int:
    """Last month's procedures, almost all completed, with their check-ins.

    Written directly (the booking service only books ahead), and audited like any other write
    of patient data. Returns how many procedures were added.
    """
    rng = random.Random(_SEED + 1)  # noqa: S311 - reproducible demo data, not a secret
    org_id = coordinator.organization_id
    system = SystemPrincipal(organization_id=org_id, job="demo_seed")
    with session_factory() as session:
        facilities = list(
            session.scalars(
                select(Facility).where(Facility.organization_id == org_id).order_by(Facility.name)
            )
        )
        procedures = list(
            session.scalars(
                select(ProcedureType)
                .where(ProcedureType.organization_id == org_id)
                .order_by(ProcedureType.code)
            )
        )
        patients = []
        for index in range(HISTORY_PATIENTS):
            patients.append(
                PatientService(session).create(
                    coordinator,
                    PatientCreate(
                        first_name=rng.choice(_FIRST_NAMES),
                        last_name=rng.choice(_LAST_NAMES),
                        date_of_birth=dt.date(
                            1950 + rng.randrange(55), rng.randrange(1, 13), rng.randrange(1, 28)
                        ),
                        phone=f"+9199901{index + 1:05d}",
                        email=f"past{index + 1}@{DEMO_EMAIL_DOMAIN}",
                        preferred_language="hi" if index % 4 == 0 else "en",
                        preferred_channel=MessageChannel.SMS,
                        consent_to_message=True,
                    ),
                    now=now,
                )
            )
        session.flush()

        tz = ZoneInfo(facilities[0].timezone)
        today = now.astimezone(tz).date()
        count = 0
        check_ins: list[CheckIn] = []
        for days_ago in range(HISTORY_DAYS, 0, -1):
            day = today - dt.timedelta(days=days_ago)
            if day.weekday() == _SUNDAY:
                continue
            for slot in sorted(rng.sample(range(SLOTS_PER_DAY), HISTORY_PER_DAY)):
                procedure = procedures[count % len(procedures)]
                start = _slot_time(day, slot, tz)
                reason = _HISTORY_CANCELLED.get(count)
                appointment = Appointment(
                    # Ids up front, so the whole month is written in two flushes.
                    id=uuid.uuid7(),
                    organization_id=org_id,
                    patient_id=patients[count % len(patients)].id,
                    facility_id=facilities[count % len(facilities)].id,
                    procedure_type_id=procedure.id,
                    scheduled_at=start,
                    arrival_at=start - dt.timedelta(hours=1),
                    duration_minutes=procedure.default_duration_minutes,
                    status=AppointmentStatus.CANCELLED if reason else AppointmentStatus.COMPLETED,
                    cancellation_reason=reason,
                    cancelled_at=start - dt.timedelta(hours=2) if reason else None,
                    completed_at=None
                    if reason
                    else start + dt.timedelta(minutes=procedure.default_duration_minutes),
                )
                session.add(appointment)
                record_audit(
                    session,
                    principal=system,
                    action=AuditAction.CREATE,
                    entity_type="appointment",
                    entity_id=appointment.id,
                    patient_id=appointment.patient_id,
                    purpose="demo_seed",
                )
                # Two readiness check-ins went out before each one; most were answered.
                for before in (dt.timedelta(days=2), dt.timedelta(days=1)):
                    answered = rng.random() < 0.88
                    sent_at = start - before
                    check_ins.append(
                        CheckIn(
                            organization_id=org_id,
                            appointment_id=appointment.id,
                            patient_id=appointment.patient_id,
                            question="Are you following your prep plan?",
                            status=CheckInStatus.ANSWERED if answered else CheckInStatus.EXPIRED,
                            response=CheckInResponse.YES if answered else None,
                            sent_at=sent_at,
                            answered_at=sent_at + dt.timedelta(hours=2) if answered else None,
                        )
                    )
                count += 1
        # The check-ins need their appointments written first.
        session.flush()
        session.add_all(check_ins)
        session.commit()
    return count


def _answer_some_check_ins(
    session_factory: sessionmaker[Session], org_id: uuid.UUID, now: dt.datetime
) -> int:
    """Confirm about two in three open check-ins; a few "no" answers on critical steps raise
    escalations through the same code path as real replies."""
    answered = 0
    system = SystemPrincipal(organization_id=org_id, job="demo_seed")
    with session_factory() as session:
        check_ins = session.scalars(
            select(CheckIn)
            .where(CheckIn.organization_id == org_id, CheckIn.status == CheckInStatus.PENDING)
            .order_by(CheckIn.created_at)
        ).all()
        for index, check_in in enumerate(check_ins):
            event = session.get(PatientTimelineEvent, check_in.timeline_event_id)
            if event is None:
                continue
            step = session.get(PrepStep, event.step_id)
            patient = session.get(Patient, check_in.patient_id)
            appointment = session.get(Appointment, check_in.appointment_id)
            if step is None or patient is None or appointment is None:
                continue
            if index % 3 == 2:
                continue
            response = (
                CheckInResponse.NO if step.is_critical and index % 6 == 0 else CheckInResponse.YES
            )
            record_answer(
                session,
                principal=system,
                patient=patient,
                appointment=appointment,
                check_in=check_in,
                event=event,
                step=step,
                response=response,
                via="in the demo",
                purpose="demo_seed",
                now=now,
            )
            answered += 1
        session.commit()
    return answered


def _add_sample_escalations(
    session_factory: sessionmaker[Session], org_id: uuid.UUID, now: dt.datetime
) -> int:
    """A chest-pain report from a patient (urgent) and a question for a nurse (normal)."""
    samples = [
        (EscalationSeverity.URGENT, "Red-flag words: CHEST_PAIN\nPatient asked: I have chest pain"),
        (
            EscalationSeverity.NORMAL,
            "The approved steps do not answer the question\n"
            "Patient asked: Can I take my usual tablet?",
        ),
    ]
    system = SystemPrincipal(organization_id=org_id, job="demo_seed")
    with session_factory() as session:
        patients = session.scalars(
            select(Patient).where(Patient.organization_id == org_id).order_by(Patient.created_at)
        ).all()
        if not patients:
            return 0
        for offset, (severity, summary) in enumerate(samples):
            patient = patients[offset % len(patients)]
            appointment = session.scalar(
                select(Appointment).where(Appointment.patient_id == patient.id).limit(1)
            )
            if appointment is None:
                continue
            red_flag = severity is EscalationSeverity.URGENT
            escalation = create_escalation(
                session,
                principal=system,
                patient=patient,
                appointment=appointment,
                severity=severity,
                summary=summary,
                purpose="demo_seed",
                source=EscalationSource.RED_FLAG if red_flag else EscalationSource.OUT_OF_PROTOCOL,
            )
            notify_staff(
                session,
                principal=system,
                patient=patient,
                appointment_id=appointment.id,
                kind=StaffNotificationKind.QUESTION,
                summary="Asked the assistant about chest pain"
                if red_flag
                else "Asked a question the prep plan does not answer",
                # A little earlier than the answers above, so the bell reads like a morning.
                now=now - dt.timedelta(minutes=12 * (offset + 1)),
                red_flag=red_flag,
                escalation=escalation,
            )
        session.commit()
    return len(samples)


def new_admin_password() -> str:
    return secrets.token_urlsafe(12)


def guest_login(session: Session, settings: Settings, *, now: dt.datetime) -> TokenPair:
    org = demo_organization(session)
    guest = guest_user(session, org) if org is not None else None
    if org is None or guest is None:
        raise AuthenticationError("The guest demo is not set up yet. Run `make seed-demo`.")
    return AuthService(session, settings).guest_session(guest, now=now)


def reset_demo_for(
    principal: StaffPrincipal, session_factory: sessionmaker[Session], *, now: dt.datetime
) -> DemoResult:
    """Regenerate the demo's patient data. Only the demo hospital's own admin may do this."""
    principal.require(Permission.DEMO_RESET)
    with session_factory() as session:
        org = session.get(Organization, principal.organization_id)
        if org is None or not org.is_demo:
            raise PermissionDeniedError("Only the demo hospital's admin can reset the demo")
    return populate_demo(session_factory, now=now, admin_password=new_admin_password())


def _demo_ready(
    session: Session, org_id: uuid.UUID, patients: list[Patient], *, now: dt.datetime
) -> list[Patient]:
    """The patients the demo works best with, falling back step by step to everyone.

    The demo raises a problem with a step, asks a question and asks to reschedule. So it needs
    a step still waiting for confirmation (a fully prepared patient has none to report), and
    no reschedule request already open (the portal offers only one). A patient who has not
    raised anything yet keeps the staff screens easy to follow.
    """
    open_steps = set(
        session.scalars(
            select(PatientTimelineEvent.patient_id)
            .join(PrepStep, PrepStep.id == PatientTimelineEvent.step_id)
            .join(Appointment, Appointment.id == PatientTimelineEvent.appointment_id)
            .where(
                PatientTimelineEvent.organization_id == org_id,
                PrepStep.requires_confirmation.is_(True),
                PatientTimelineEvent.status.not_in(
                    [
                        TimelineEventStatus.CONFIRMED,
                        TimelineEventStatus.CANCELLED,
                        TimelineEventStatus.SKIPPED,
                    ]
                ),
                Appointment.scheduled_at > now,
            )
        )
    )
    waiting = set(
        session.scalars(
            select(Task.patient_id).where(
                Task.organization_id == org_id,
                Task.type == TaskType.RESCHEDULE,
                Task.status.in_([TaskStatus.OPEN, TaskStatus.IN_PROGRESS]),
            )
        )
    )
    raised = set(
        session.scalars(
            select(StaffNotification.patient_id).where(StaffNotification.organization_id == org_id)
        )
    )
    tiers = (
        [p for p in patients if p.id in open_steps and p.id not in waiting | raised],
        [p for p in patients if p.id in open_steps and p.id not in waiting],
        [p for p in patients if p.id not in waiting],
    )
    return next((tier for tier in tiers if tier), patients)


